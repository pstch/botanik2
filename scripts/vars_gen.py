#!/usr/bin/env python3
"""The variable tables: CSV in, C++ out.

Emits the same `constexpr` factory calls the tables used to be written as, so
`vars/declare.h` stays the one definition of what a scope means and the flash
placement is unchanged. Output is committed, never built: the tree has no Python
build dependency and an Arduino sketch path could not run a generator.

    python3 scripts/vars_gen.py             # write the generated C++
    python3 scripts/vars_gen.py --check     # fail if it would differ (check-vars)
    python3 scripts/vars_gen.py --format    # rewrite the CSVs column-aligned
"""

import argparse
import os
import re
import sys
from collections import OrderedDict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vars_csv
import vars_checks
import vars_devices
import vars_programs

from vars_extract import FACTORIES, FILES, CAL_FIELDS, GATE

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The vocabularies of the table set being generated, so call_args() can tell a
# generated converter from a hand-written one. Set by gen_site().
ENUMS = {}

BANNER = ("GENERATED by scripts/vars_gen.py from {src} - do not edit.",
          "Edit the CSVs and re-run, or `make -C build check-vars` will fail.")

# Parameters carrying a C++ string literal rather than a bare token.
QUOTED = {"name", "code", "unit", "desc", "notes", "kind_str"}
# Parameters the factory takes as a Scalar, which the CSV holds unwrapped. The
# row's own `type` column picks the wrapper; AI is always T_F32 by construction.
SCALARS = {
    "G":  ["def"], "GR": ["def"],
    "MI": ["min", "max", "fallback"],
    "AI": ["fallback"],
    "MO": ["safe"],
}
# Trailing parameters a call may simply omit, and what the factory defaults them
# to when a later one forces them to be spelled.
OPTIONAL = {"poll": "0", "word_swap": "false", "access": "true",
            "_pulse": "false"}

# What a parameter's `access` cell may say, and the `writable` bool it becomes.
# Empty is RW, so the column stays blank on the rows nobody has thought about.
ACCESS = {"": "true", "RW": "true", "RO": "false"}


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def wrap_scalar(value, vtype):
    """A bare number as the Scalar its row's type names."""
    if not value:
        return "Scalar()"
    if vtype == "T_F32":
        return f"SF({value}{'' if value.endswith('f') else 'f'})"
    if vtype == "T_BOOL":
        return f"SB({value})"
    if vtype in ("T_I8", "T_I16", "T_I32", "T_I64"):
        return f"SI({value})"
    return f"SU({value})"


def tunable(cell):
    """param@default -> R("param", defaultf) ; =const -> K(constf)"""
    if cell.startswith("="):
        v = cell[1:]
        return f"K({v}{'' if v.endswith('f') else 'f'})"
    name, _, dflt = cell.partition("@")
    dflt = dflt or "0.0"
    return f'R({quote(name)}, {dflt}{"" if dflt.endswith("f") else "f"})'


def cal_name(row):
    """One block per analog row, named after it: sharing is expressed by naming
    the same parameters, not by pointing at the same object."""
    return "CAL_" + row["name"]


def call_args(kind, row):
    """The factory's arguments, in order, as C++ tokens."""
    params = list(FACTORIES[kind])
    vtype = row.get("type", "")
    out = []
    for p in params:
        if p == "cal":
            out.append("&" + cal_name(row))
            continue
        if p == "_pulse":
            # Not a column: F_PULSE is what `isr` MEANS to the row, where the
            # edge itself only reaches the site's pulse table.
            out.append("true" if row.get("isr") else None)
            continue
        cell = row.get(p, "")
        if p in QUOTED or (p == "def" and kind == "PS"):
            out.append(quote(cell))
        elif p in SCALARS.get(kind, []):
            out.append(wrap_scalar(cell, "T_F32" if kind == "AI" else vtype))
        elif p == "access":
            out.append(ACCESS.get(cell, "true"))
        elif p == "str":
            if not cell:
                out.append("nullptr")
            else:
                out.append("&" + (cell + "_label" if cell in ENUMS else cell))
        elif not cell and p in OPTIONAL:
            out.append(None)                     # maybe droppable, decided below
        else:
            if not cell:
                sys.exit(f"{kind}({row['name']}): column '{p}' is empty and required")
            out.append(cell)

    # Drop trailing optionals the call does not need; spell any that an argument
    # after them forces.
    while out and out[-1] is None:
        out.pop()
        params.pop()
    return [a if a is not None else OPTIONAL[params[i]] for i, a in enumerate(out)], params


def emit_rows(kind_of_row, indent="    "):
    """A run of factory calls, column-aligned the way the C++ they replace was."""
    calls = [(k, *call_args(k, r), r) for k, r in kind_of_row]
    if not calls:
        return []
    width = {}
    for kind, args, params, _ in calls:
        for p, a in zip(params, args):
            if p not in ("desc", "notes"):
                width[p] = max(width.get(p, 0), len(a))
    lines = []
    for kind, args, params, row in calls:
        parts = [a.ljust(width[p]) if p in width else a for p, a in zip(params, args)]
        lines.append(f"{indent}{kind}({', '.join(parts).rstrip()}),")
    return lines


def gate_runs(rows):
    """Consecutive rows sharing a feature gate, so one #if wraps the run."""
    runs, cur, gate = [], [], None
    for item in rows:
        g = item[1].get(GATE, "")
        if g != gate and cur:
            runs.append((gate, cur))
            cur = []
        gate, = (g,)
        cur.append(item)
    if cur:
        runs.append((gate, cur))
    return runs


def array(name, rows, count_name):
    """One `const Descriptor[]`, its gated runs, and its count."""
    out = [f"const Descriptor {name}[] = {{"]
    for gate, run in gate_runs(rows):
        if gate:
            out.append(f"#if {gate}")
        out += emit_rows(run)
        if gate:
            out.append("#endif")
    out += ["};",
            f"const uint16_t {count_name} = "
            f"(uint16_t)(sizeof({name}) / sizeof({name}[0]));", ""]
    return out


def load_enums(table_dir):
    """The enumerated vocabularies, as {enum: [member rows]} in file order."""
    path = os.path.join(table_dir, "enums.csv")
    if not os.path.exists(path):
        return {}
    out = OrderedDict()
    for r in vars_csv.read(path):
        r["_set"] = os.path.basename(os.path.dirname(table_dir))
        out.setdefault(r["enum"], []).append(r)
    return out


def emit_enums(enums):
    """One C++ enum and one converter per vocabulary.

    Together, so the type and its labels cannot part - which is what they did
    when the enum lived in tasks.h and the switch in vars.cpp. The converter
    answers null for an unmapped code, which is what REFUSES it: PE()'s whole
    bound is its vocabulary.
    """
    if not enums:
        return []
    out = ["/** @name Enumerations",
           " *  Generated from tables/enums.csv. A CODE is the contract an",
           " *  external master reads; a LABEL is what an operator types.",
           " *  @{ */", ""]
    for name, members in enums.items():
        width = max(len(m["member"]) for m in members)
        out += [f"enum {name} : uint8_t {{"]
        for m in members:
            line = f"    {m['member'].ljust(width)} = {m['code']},"
            out.append(line + (f"   ///< {m['desc']}" if m.get("desc") else ""))
        out += ["};", ""]
        out += [f"/** @brief A {name} as the word an operator reads and types.",
                " *  Null for an unmapped code, which is what refuses it. */",
                f"inline const char* {name}_label(uint64_t code) {{",
                "    switch (code) {"]
        for m in members:
            out.append(f"        case {m['code']}: return \"{m['label']}\";")
        out += ["        default: return nullptr;", "    }", "}", ""]
    return out + ["/** @} */", ""]


def load(table_dir, setname=""):
    """Every table in a directory, as (factory, row) pairs, in file order."""
    out = {}
    for fname, (kinds, _) in FILES.items():
        path = os.path.join(table_dir, fname)
        if not os.path.exists(path) or not kinds:
            continue
        for r in vars_csv.read(path):
            kind = r.get("scope") or (("GR" if r.get("retain") else "G")
                                      if fname == "globals.csv" else kinds[0])
            r["_set"] = setname or os.path.basename(os.path.dirname(table_dir))
            out.setdefault(fname, []).append((kind, r))
    return out


def var_max(site):
    """The site's BOTANIK_VAR_MAX, or None when it takes the default."""
    path = os.path.join(ROOT, "src", "sites", site, "config.h")
    if not os.path.exists(path):
        return None
    m = re.search(r"^\s*#\s*define\s+BOTANIK_VAR_MAX\s+(\d+)",
                  open(path, encoding="utf-8").read(), re.M)
    return int(m.group(1)) if m else None


def site_mentions(site):
    """Every quoted identifier in the site's HAND-WRITTEN C++.

    A row the site animates in `sim.h` or reaches for in `vars.cpp` is used,
    whatever programs.toml says about it - and a name is how it does that. Wide
    on purpose: this only ever SUPPRESSES a finding, so a false positive costs a
    check that does not fire and a false negative would cost a wrong error.
    """
    out = set()
    d = os.path.join(ROOT, "src", "sites", site)
    if not os.path.isdir(d):
        return out
    for f in sorted(os.listdir(d)):
        if not f.endswith((".h", ".cpp")):
            continue
        text = open(os.path.join(d, f), encoding="utf-8").read()
        out |= set(re.findall(r'"([A-Za-z_][A-Za-z_0-9]*)"', text))
    return out


def cal_params(rows):
    """The parameters an analog calibration names. Read by the MODEL rather than
    by a program, so nothing in programs.toml mentions them."""
    out = set()
    for _, r in rows:
        for f in CAL_FIELDS:
            cell = r.get(f, "")
            if cell and not cell.startswith("="):
                out.add(cell.split("@")[0])
    return out


def banner(src, fname="vars.gen.h"):
    return ["/**", f" * @file {fname}",
            f" * @brief {BANNER[0].format(src=src)}",
            f" *        {BANNER[1]}", " */", ""]


def gen_site(site):
    table_dir = os.path.join(ROOT, "src", "sites", site, "tables")
    tables = load(table_dir, site)
    enums = load_enums(table_dir)
    global ENUMS
    ENUMS = enums
    analog = tables.get("analog_inputs.csv", []) + tables.get("analog_outputs.csv", [])

    out = ["#ifndef SITE_VARS_GEN_H", "#define SITE_VARS_GEN_H", ""]
    out = banner(f"the CSV tables in src/sites/{site}/tables/") + out
    out += ["#include <cstdint>", "", '#include "libbotanik.h"', "",
            "namespace Site {", "", "using namespace Botanik;",
            "using namespace Botanik::Vars;", ""]

    # FIRST: a row takes the address of its converter, which is defined here.
    out += emit_enums(enums)

    if analog:
        out += ["/** @name Analog calibration - one block per row.",
                " *  Two rows sharing a calibration name the same six parameters, which",
                " *  resolve to the same rows: sharing is in the names, not in an object.",
                " *  @{ */", ""]
        for _, r in analog:
            vals = ",\n    ".join(tunable(r[f]) for f in CAL_FIELDS)
            out += [f"const AnalogCal {cal_name(r)} = {{", f"    {vals},", "};"]
        out += ["", "const AnalogCal* const g_analog_cals[] = {"]
        out += [f"    &{cal_name(r)}," for _, r in analog]
        out += ["};", "const uint8_t g_analog_cal_count =",
                "    (uint8_t)(sizeof(g_analog_cals) / sizeof(g_analog_cals[0]));",
                "", "/** @} */", ""]

    # A converter this table names that is NOT one of the generated ones: a
    # library vocabulary is `Logs::level_label`, and a site may still write
    # one by hand. Declared here so a row can take the address.
    converters = sorted({r["str"] for items in tables.values() for _, r in items
                         if r.get("str") and "::" not in r["str"]
                         and r["str"] not in enums})
    if converters:
        out += ["/** @brief Enum converters this table names and this file does",
                " *  not generate. The site defines them. */"]
        out += [f"const char* {c}(uint64_t);" for c in converters] + [""]

    out += ["/** @brief The editable rows. FIRST, and that is load-bearing: the",
            " *  ROLE_PARAM run has to stay contiguous with the library's. */"]
    out += array("params", tables.get("params.csv", []), "PARAMS_COUNT")

    rest = [item for f in FILES if f != "params.csv" for item in tables.get(f, [])]
    out += ["/** @brief Everything else, in file order. Alarms lead, so their table",
            " *  order - which is the order the ALARMS page lists them in - is the",
            " *  order alarms.csv gives them. */"]
    out += array("rows", rest, "ROWS_COUNT")

    pulses = [r for _, r in tables.get("digital_inputs.csv", []) if r.get("isr")]
    if pulses:
        out += ["/** @brief The local inputs counted by an interrupt rather than",
                " *  polled. Generated from the `isr` column, so the channel a row",
                " *  declares and the channel the firmware attaches cannot part. */",
                "struct PulseInput { const char* name; uint8_t channel; "
                "HAL::Pulse::Edge edge; };",
                "const PulseInput pulse_inputs[] = {"]
        for r in pulses:
            out.append(f'    {{ {quote(r["name"])}, {r["reg"]}, '
                       f'HAL::Pulse::{vars_checks.EDGES[r["isr"]]} }},')
        out += ["};", "const uint8_t pulse_input_count =",
                "    (uint8_t)(sizeof(pulse_inputs) / sizeof(pulse_inputs[0]));", ""]

    out += vars_devices.emit(*vars_devices.load(table_dir))

    out += ["/** @brief Hand the bank this site's rows, parameters first. Generated so",
            " *  the ordering rule is held by the tool rather than by a comment. */",
            "inline void register_all(Vars::Bank& io) {",
            "    io.register_vars(params, PARAMS_COUNT);",
            "    io.register_vars(rows,   ROWS_COUNT);",
            "}", "", "}  // namespace Site", "", "#endif  // SITE_VARS_GEN_H"]
    return "\n".join(out) + "\n"


def gen_library():
    tables = load(os.path.join(ROOT, "src", "libbotanik", "vars", "tables"), "libbotanik")
    # PARAMETERS LAST, and this is the whole of lib_order: the library registers
    # before any site, so its parameter run has to END where the site's begins or
    # Bank::freeze() finds the site's stranded outside the block.
    order = [f for f in FILES if f != "params.csv"] + ["params.csv"]
    rows = [item for f in order for item in tables.get(f, [])]

    out = banner("the CSV tables in src/libbotanik/vars/tables/")
    out += ["#ifndef LIBBOTANIK_VARS_GEN_H", "#define LIBBOTANIK_VARS_GEN_H", "",
            "// Included by vars/vars.cpp, AFTER the feature-gated includes its row",
            "// defaults read. Not a standalone header.", "",
            "namespace Botanik { namespace Vars {", ""]
    out += ["/** @brief The library's own rows. Its PARAMETERS come last, so a site's",
            " *  parameter segment abuts them. @see lib_order */"]
    out += array("library_vars", rows, "LIBRARY_VARS_COUNT")
    out += ["}}  // namespace Botanik::Vars", "", "#endif  // LIBBOTANIK_VARS_GEN_H"]
    return "\n".join(out) + "\n"


def put(path, text, check):
    """Write, or report a difference. @return whether anything differed."""
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    rel = os.path.relpath(path, ROOT)
    if old == text:
        print(f"  {rel}: up to date")
        return False
    if check:
        print(f"  {rel}: OUT OF DATE", file=sys.stderr)
        return True
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(text)
    print(f"  {rel}: {'written' if old is None else 'updated'}")
    return False


def reformat(table_dir):
    for fname, (_, base) in FILES.items():
        path = os.path.join(table_dir, fname)
        if not os.path.exists(path):
            continue
        header = vars_csv.header_of(path)
        rows = vars_csv.read(path)
        pre = [l.lstrip("# ").rstrip() for l in open(path, encoding="utf-8")
               if l.lstrip().startswith("#")]
        vars_csv.write(path, header, rows, preamble=[p for p in pre if p])
        print(f"  {os.path.relpath(path, ROOT)}: {len(rows)} rows aligned")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the output would differ")
    ap.add_argument("--format", action="store_true", help="rewrite the CSVs aligned")
    ap.add_argument("--site", default="gh_mlb41")
    a = ap.parse_args()

    if a.format:
        print("Formatting tables:")
        reformat(os.path.join(ROOT, "src", "sites", a.site, "tables"))
        reformat(os.path.join(ROOT, "src", "libbotanik", "vars", "tables"))
        return

    problems = []
    both = []
    for d, name in ((os.path.join(ROOT, "src", "sites", a.site, "tables"), a.site),
                    (os.path.join(ROOT, "src", "libbotanik", "vars", "tables"),
                     "libbotanik")):
        for items in load(d, name).values():
            both += items
    print(f"Checking {len(both)} rows:")
    vars_checks.check(both, problems.append)
    site_enums = load_enums(os.path.join(ROOT, "src", "sites", a.site, "tables"))
    members = [m for ms in site_enums.values() for m in ms]
    if members:
        print(f"Checking {len(site_enums)} enums, {len(members)} members:")
    vars_checks.enums(members, both, problems.append)
    vars_checks.capacity(both, var_max(a.site), problems.append)

    site_dir = os.path.join(ROOT, "src", "sites", a.site, "tables")
    models, devices = vars_devices.load(site_dir)
    if devices:
        print(f"Checking {len(devices)} field devices, {len(models)} models:")
        vars_devices.check(models, devices, both, problems.append)

    # The configuration, against the table it connects to. A row's SCOPE is what
    # says whether a program may produce it, so this cannot run until both sets
    # of tables are loaded.
    effective, _ = vars_checks._shadows(both, problems.append)
    by_name = {r["name"]: (k, r) for k, r in effective}
    progs = vars_programs.load(os.path.join(ROOT, "src", "sites", a.site,
                                            "tables", "programs.toml"))
    if progs:
        print(f"Checking {len(progs)} programs, "
              f"{sum(len(x['conns']) for x in progs)} connections:")
        vars_programs.check(progs, by_name, problems.append,
                            site_mentions(a.site), cal_params(both),
                            {r["name"] for _, r in both
                             if r.get("_set") == "libbotanik"})
    for p in problems:
        print("  " + p, file=sys.stderr)
    if problems:
        sys.exit(f"\n{len(problems)} problem(s) in the variable tables")
    print("  no problems")

    print("Generating:")
    stale = put(os.path.join(ROOT, "src", "sites", a.site, "generated", "vars.gen.h"),
                gen_site(a.site), a.check)
    stale |= put(os.path.join(ROOT, "src", "libbotanik", "vars", "generated", "vars.gen.h"),
                 gen_library(), a.check)
    if progs:
        stale |= put(os.path.join(ROOT, "src", "sites", a.site, "generated",
                                  "programs.gen.h"),
                     vars_programs.generate(
                         progs, by_name,
                         banner("the site's tables/programs.toml",
                                "programs.gen.h")),
                     a.check)
    if stale:
        sys.exit("\nthe generated C++ is out of date: run python3 scripts/vars_gen.py")


if __name__ == "__main__":
    main()
